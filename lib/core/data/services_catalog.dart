import 'package:flutter/material.dart';

/// A service category of the Allo Service catalog.
class ServiceCategoryData {
  final String id;
  final String nameFr;
  final String nameAr;

  /// Fallback icon when the category PNG asset is missing.
  final IconData icon; // ← added (Phase 6-2c-1A)

  const ServiceCategoryData({
    required this.id,
    required this.nameFr,
    required this.nameAr,
    required this.icon,
  });
}

/// A single bookable service of the catalog.
class ServiceItem {
  final String id;
  final String nameAr;
  final String nameFr;
  final String categoryId;

  /// Local asset path (French slug — may differ from [id]):
  /// `assets/services/<slug>.png`.
  ///
  /// Files are auto-generated (Icons8 CDN); when a file is missing at
  /// runtime the UI falls back to [icon].
  final String imagePath;
  final IconData icon;

  const ServiceItem({
    required this.id,
    required this.nameAr,
    required this.nameFr,
    required this.categoryId,
    required this.imagePath,
    required this.icon,
  });
}

